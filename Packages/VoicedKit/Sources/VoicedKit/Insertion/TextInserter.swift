import AppKit

public enum TextInsertionError: Error, Equatable, LocalizedError, Sendable {
    case accessibilityNotGranted
    case keystrokeUnavailable

    public var errorDescription: String? {
        switch self {
        case .accessibilityNotGranted:
            "Voiced needs Accessibility access to paste. The text is on your clipboard: press ⌘V."
        case .keystrokeUnavailable:
            "Could not send the paste keystroke. The text is on your clipboard: press ⌘V."
        }
    }
}

@MainActor
public protocol TextInserting: AnyObject {
    /// Puts `text` into the focused app.
    func insert(_ text: String) async throws
}

/// Synthesizes ⌘V for the focused app.
public enum PasteKeystroke {
    /// Stamped on the events Voiced posts so its own hotkey monitor can skip them.
    public static let eventMarker: Int64 = 0x56_6F_69_63_65_64

    private static let virtualKeyV: CGKeyCode = 9

    @MainActor
    public static func post() throws {
        guard AXIsProcessTrusted() else {
            throw TextInsertionError.accessibilityNotGranted
        }
        let source = CGEventSource(stateID: .combinedSessionState)
        guard
            let keyDown = CGEvent(keyboardEventSource: source, virtualKey: virtualKeyV, keyDown: true),
            let keyUp = CGEvent(keyboardEventSource: source, virtualKey: virtualKeyV, keyDown: false)
        else {
            throw TextInsertionError.keystrokeUnavailable
        }
        for event in [keyDown, keyUp] {
            // Explicit flags, so a modifier the user still holds does not turn ⌘V into something else.
            event.flags = .maskCommand
            event.setIntegerValueField(.eventSourceUserData, value: eventMarker)
            event.post(tap: .cghidEventTap)
        }
    }
}

/// Inserts text by placing it on the pasteboard, pasting, and then putting the old contents back.
///
/// Pasting is the one insertion method that works across native, Electron and web text fields.
@MainActor
public final class PasteboardTextInserter: TextInserting {
    private typealias Snapshot = [[NSPasteboard.PasteboardType: Data]]

    private struct PendingRestore {
        var task: Task<Void, Never>
        var snapshot: Snapshot
        var changeCount: Int
    }

    private let pasteboard: NSPasteboard
    private let postPaste: @MainActor () throws -> Void
    private let restoreDelay: Duration
    private var pendingRestore: PendingRestore?

    /// Clipboard managers skip pasteboard contents that carry these marker types (nspasteboard.org).
    private static let markerTypes = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    /// - Parameter restoreDelay: How long the focused app gets to read the pasteboard before the
    ///   previous contents come back.
    public init(
        pasteboard: NSPasteboard = .general,
        restoreDelay: Duration = .milliseconds(800),
        postPaste: @escaping @MainActor () throws -> Void = { try PasteKeystroke.post() }
    ) {
        self.pasteboard = pasteboard
        self.restoreDelay = restoreDelay
        self.postPaste = postPaste
    }

    public func insert(_ text: String) async throws {
        restorePendingNow()
        let snapshot = Self.snapshot(of: pasteboard)

        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        for type in Self.markerTypes {
            item.setData(Data(), forType: type)
        }
        pasteboard.clearContents()
        pasteboard.writeObjects([item])
        let changeCount = pasteboard.changeCount

        let log = VoicedLog.insertion
        // If this throws, the text stays on the pasteboard so the user can paste it by hand.
        do {
            try postPaste()
        } catch {
            log.error("path: pasteboard only. The ⌘V keystroke was not posted (\(VoicedLog.describe(error), privacy: .public)); chars=\(text.count) left on the clipboard")
            throw error
        }
        log.notice("path: pasteboard + ⌘V keystroke posted, chars=\(text.count); \(snapshot.count) previous clipboard item(s) to restore")

        let delay = restoreDelay
        let task = Task { [weak self] in
            try? await Task.sleep(for: delay)
            guard !Task.isCancelled else { return }
            self?.restorePendingNow()
        }
        pendingRestore = PendingRestore(task: task, snapshot: snapshot, changeCount: changeCount)
    }

    private func restorePendingNow() {
        guard let pending = pendingRestore else { return }
        pendingRestore = nil
        pending.task.cancel()
        // Something else was copied in the meantime; leave it alone.
        guard pasteboard.changeCount == pending.changeCount else {
            VoicedLog.insertion.notice("clipboard changed since the paste; previous contents not restored")
            return
        }
        VoicedLog.insertion.notice("previous clipboard restored, items=\(pending.snapshot.count)")
        pasteboard.clearContents()
        let items = pending.snapshot.map { contents in
            let item = NSPasteboardItem()
            for (type, data) in contents {
                item.setData(data, forType: type)
            }
            return item
        }
        if !items.isEmpty {
            pasteboard.writeObjects(items)
        }
    }

    private static func snapshot(of pasteboard: NSPasteboard) -> Snapshot {
        (pasteboard.pasteboardItems ?? []).map { item in
            var contents: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                contents[type] = item.data(forType: type)
            }
            return contents
        }
    }
}
